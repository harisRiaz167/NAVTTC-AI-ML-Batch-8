# Task 13 — Nested if statement
i = int(input("Enter an integer: "))
if i == 10:
    if i < 15:
        print("i is smaller than 15")
    if i < 12:
        print("i is smaller than 12 too")
    else:
        print("i is greater than or equal to 12")
else:
    print("i is not equal to 10")
